// Dashboard deployment needs one self-contained file; CLI deployment uses the
// original index.ts and shared modules. No environment values enter the bundle.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const base = 'supabase/functions/';
const http = readFileSync(base + '_shared/http.ts', 'utf8');
const security = readFileSync(base + '_shared/counter-security.ts', 'utf8');
const handler = readFileSync(base + 'balcao-api/index.ts', 'utf8').replace(/^import .* from '\.\.\/_shared\/.*';\r?\n/gm, '');
mkdirSync('supabase/deploy', { recursive: true });
writeFileSync('supabase/deploy/balcao-api.ts', '// Generated by scripts/bundle-counter-function.mjs. Do not edit.\n' + http + '\n' + security + '\n' + handler);
console.log('Prepared self-contained balcao-api deployment file.');
