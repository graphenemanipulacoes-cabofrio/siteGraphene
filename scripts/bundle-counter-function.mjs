// Dashboard deployment needs one self-contained file; CLI deployment uses the
// original index.ts and shared modules. No environment values enter the bundle.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const base = 'supabase/functions/';
const http = readFileSync(base + '_shared/http.ts', 'utf8');
const security = readFileSync(base + '_shared/counter-security.ts', 'utf8');
mkdirSync('supabase/deploy', { recursive: true });
for (const name of ['balcao-api', 'admin-login']) {
  const handler = readFileSync(base + name + '/index.ts', 'utf8').replace(/^import .* from '\.\.\/_shared\/.*';\r?\n/gm, '');
  writeFileSync(`supabase/deploy/${name}.ts`, '// Generated by scripts/bundle-counter-function.mjs. Do not edit.\n' + http + '\n' + security + '\n' + handler);
}
console.log('Prepared self-contained balcao-api and admin-login deployment files.');
